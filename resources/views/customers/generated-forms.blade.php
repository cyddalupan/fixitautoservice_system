    }
    
    function downloadQR(url, token) {
        const qrUrl = 'https://api.qrserver.com/v1/create-qr-code/?size=500x500&data=' + encodeURIComponent(url);
        // Use canvas to download cross-origin image reliably
        const img = new Image();
        img.crossOrigin = 'anonymous';
        img.onload = function() {
            const c = document.createElement('canvas');
            c.width = img.width;
            c.height = img.height;
            const ctx = c.getContext('2d');
            ctx.drawImage(img, 0, 0);
            const link = document.createElement('a');
            link.download = 'customer-form-' + token.substring(0, 8) + '-qr.png';
            link.href = c.toDataURL('image/png');
            document.body.appendChild(link);
            link.click();
            document.body.removeChild(link);
        };
        img.onerror = function() {
            // Fallback: direct download attempt
            const link = document.createElement('a');
            link.href = qrUrl;
            link.download = 'customer-form-' + token.substring(0, 8) + '-qr.png';
            document.body.appendChild(link);
            link.click();
            document.body.removeChild(link);
        };
        img.src = qrUrl;
    }

    function downloadQrImage(qrUrl, filename) {
        // Generic QR download: canvas-based to bypass CORS issues
        if (!qrUrl) return;
        const img = new Image();
        img.crossOrigin = 'anonymous';
        img.onload = function() {
            const c = document.createElement('canvas');
            c.width = img.width;
            c.height = img.height;
            const ctx = c.getContext('2d');
            ctx.drawImage(img, 0, 0);
            const link = document.createElement('a');
            link.download = filename || 'qr-code.png';
            link.href = c.toDataURL('image/png');
            document.body.appendChild(link);
            link.click();
            document.body.removeChild(link);
        };
        img.onerror = function() {
            const link = document.createElement('a');
            link.href = qrUrl;
            link.download = filename || 'qr-code.png';
            document.body.appendChild(link);
            link.click();
            document.body.removeChild(link);
        };
        img.src = qrUrl;
    }

    function copyQrImage(qrUrl) {
        // Copy QR image to clipboard using canvas
        if (!qrUrl) return;
        const img = new Image();
        img.crossOrigin = 'anonymous';
        img.onload = function() {
            const c = document.createElement('canvas');
            c.width = img.width;
            c.height = img.height;
            const ctx = c.getContext('2d');
            ctx.drawImage(img, 0, 0);
            c.toBlob(function(blob) {
                if (!blob) return;
                navigator.clipboard.write([
                    new ClipboardItem({ 'image/png': blob })
                ]).then(function() {
                    alert('QR code copied to clipboard!');
                }).catch(function() {
                    // Fallback: download
                    const link = document.createElement('a');
                    link.download = 'qr-code.png';
                    link.href = c.toDataURL('image/png');
                    document.body.appendChild(link);
                    link.click();
                    document.body.removeChild(link);
                });
            });
        };
        img.onerror = function() {
            alert('Failed to load QR code image for copying. Try downloading instead.');
        };
        img.src = qrUrl;
    }

