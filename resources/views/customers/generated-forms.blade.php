    function saveFormEmail() {
        const email = document.getElementById('editEmailInput').value.trim();
        if (!email) {
            alert('Please enter an email address.');
            return;
        }
        
        const saveBtn = document.getElementById('saveEmailBtn');
        saveBtn.disabled = true;
        saveBtn.innerHTML = '<span class="spinner-border spinner-border-sm me-1"></span> Saving...';
        
        fetch('{{ url("/api/customer-form") }}/' + currentEditToken + '/email', {
            method: 'PUT',
            headers: {
                'Content-Type': 'application/json',
                'X-CSRF-TOKEN': '{{ csrf_token() }}',
                'Accept': 'application/json'
            },
            body: JSON.stringify({ email: email })
        })
        .then(response => response.json())
        .then(data => {
            if (data.success) {
                // Update the modal and the list
                document.getElementById('generatedFormEmail').value = email;
                
                const editModalEl = document.getElementById('editEmailModal');
                const editModal = bootstrap.Modal.getInstance(editModalEl);
                if (editModal) editModal.hide();
                
                // Refresh the page to update the list
                window.location.reload();
            } else {
                alert('Error: ' + data.message);
                saveBtn.disabled = false;
                saveBtn.innerHTML = '<i class="fas fa-save me-1"></i> Save Email';
            }
        })
        .catch(error => {
            console.error('Error:', error);
            alert('Network error. Please try again.');
            saveBtn.disabled = false;
            saveBtn.innerHTML = '<i class="fas fa-save me-1"></i> Save Email';
        });
    }

